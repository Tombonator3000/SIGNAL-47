import json,sys,hashlib
from pathlib import Path
import argparse
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parent/'freemodels'));import trim_web as h
parser=argparse.ArgumentParser(description='Prepare only SARO grime overlay geometry from the original export; no engine or DCC launch.')
