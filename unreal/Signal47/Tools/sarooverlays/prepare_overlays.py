 lines.append(f'static const FOverlayVertex Grime{g}[] = {{');lines.extend(rows);lines.append('};')
 report[g]={'triangles':len(ids)//3,'moved_vertices':moved,'source_sha256':hashlib.sha256((export/'geo'/f['file']).read_bytes()).hexdigest()}
