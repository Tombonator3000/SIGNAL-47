"""Bind the nine physical research sheets to reviewed art, without editing images."""
from pathlib import Path
import hashlib
import importlib.util
import json
from PIL import Image

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[1]
SOURCE = PROJECT.parent / 'ArtSource/Office'
spec = importlib.util.spec_from_file_location('research_dressing', SOURCE / 'research_dressing.py')
dressing = importlib.util.module_from_spec(spec)
spec.loader.exec_module(dressing)
DEST = '/Game/Signal47/Art/Office/Reference'
DOCS = '/Game/Signal47/Art/Documents'


def asset(root, name):
    return f'{root}/{name}.{name}'


# Image coordinates are top-left based. Native MapU/MapV handle the wall plane.
BINDINGS = {
    'ArrayMap': (asset(DEST, 'T_OfficeResearch_Map'), (0, 0, 1, 1)),
    'ClippingLeft': (asset(DOCS, 'T_Doc_DaleClippings'), (0, 0, .864, .47)),
    'ClippingRight': (asset(DOCS, 'T_Doc_DaleClippings'), (0, .47, 1, 1)),
    'FieldPhoto': (asset(DEST, 'T_OfficeResearch_Photos'), (0, .05, .5, .45)),
    'PhotoPair': (asset(DEST, 'T_OfficeResearch_Photos'), (0, .55, .5, .921)),
    'WorkingNote': (asset(DOCS, 'T_Doc_DaleNote'), (0, 0, 1, .72)),
    'FieldCard': (asset(DOCS, 'T_Doc_DaleIndex'), (0, 0, 1, .8203)),
    'ContactStrip': (asset(DEST, 'T_OfficeResearch_Photos'), (.5, .13, 1, .35857)),
    'ShiftNote': (asset(DOCS, 'T_Doc_DaleContact'), (0, 0, 1, .875)),
}


def main():
    textures = []
    for name, file in (('T_OfficeResearch_Map', 'research_array_map.png'),
                       ('T_OfficeResearch_Photos', 'research_photo_atlas.png')):
        path = SOURCE / 'textures' / file
        with Image.open(path) as image:
            size = list(image.size)
        textures.append({'name': name, 'source': 'textures/' + file, 'size': size,
                         'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    rows, lines = [], ['// Generated by Tools/interiors/build_reference_bindings.py. No gameplay documents are granted.']
    for surface in dressing.SURFACES:
        key = surface['name'].split(':')[-1]
        path, crop = BINDINGS[key]
        assert surface['normal_axis'] == (-1, 0, 0)
        x, y, z = surface['centre']
        w, h, roll = surface['width_m'], surface['height_m'], surface['roll_degrees']
        values = ', '.join(f'{value:.9g}' for value in (w, h, roll, *crop))
        lines.append(f' {{TEXT("{surface["name"]}"), TEXT("{path}"), FVector({x:.9g}, {y:.9g}, {z:.9g}), {values}}},')
        rows.append({**surface, 'texture_asset': path, 'image_crop': crop})
    assert len(rows) == len(BINDINGS) == 9
    header = PROJECT / 'Source/Signal47/Private/S47OfficeResearchData.inl'
    header.write_text('\n'.join(lines) + '\n')
    report = {'version': 1, 'scope': 'Decorative references only; original live document IDs/read state unchanged',
              'destination': DEST, 'textures': textures, 'surfaces': rows,
              'native_import': 'UNVERIFIED', 'runtime_appearance': 'UNVERIFIED'}
    (SOURCE / 'research-art-bindings.json').write_text(json.dumps(report, indent=2) + '\n')
    print(f'Nine research art bindings generated; {len(textures)} new source textures, original document textures reused')


if __name__ == '__main__':
    main()
