"""Sample the original exported SARO ground for one non-walkable visual seam.

No Blender/UE process or asset import. Writes original numeric source data only.
Input is the unchanged Three-metre web export, not an Unreal vertex conversion.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct


def triangles(path, name):
    data = path.read_bytes()
    length, kind = struct.unpack_from('<II', data, 12)
    assert kind == 0x4e4f534a
    doc = json.loads(data[20:20 + length])
    binary_length, kind = struct.unpack_from('<II', data, 20 + length)
    assert kind == 0x004e4942
    binary = data[28 + length:28 + length + binary_length]

    def array(index):
        accessor = doc['accessors'][index]
        view = doc['bufferViews'][accessor['bufferView']]
        count = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4}[accessor['type']]
        fmt = '<' + {5126: 'f', 5125: 'I', 5123: 'H', 5121: 'B'}[accessor['componentType']] * count
        offset = view.get('byteOffset', 0) + accessor.get('byteOffset', 0)
        stride = view.get('byteStride', struct.calcsize(fmt))
        return [struct.unpack_from(fmt, binary, offset + i * stride) for i in range(accessor['count'])]

    mesh = next(item for item in doc['meshes'] if item.get('name') == name)
    result = []
    for primitive in mesh['primitives']:
        points = array(primitive['attributes']['POSITION'])
        indices = [value[0] for value in array(primitive['indices'])]
        result.extend(tuple(points[i] for i in indices[j:j + 3]) for j in range(0, len(indices), 3))
    return result


def height(mesh, x, z):
    hits = []
    for a, b, c in mesh:
        if not min(a[0], b[0], c[0]) - 1e-6 <= x <= max(a[0], b[0], c[0]) + 1e-6:
            continue
        if not min(a[2], b[2], c[2]) - 1e-6 <= z <= max(a[2], b[2], c[2]) + 1e-6:
            continue
        dx, dz, ex, ez = b[0] - a[0], b[2] - a[2], c[0] - a[0], c[2] - a[2]
        determinant = dx * ez - dz * ex
        if abs(determinant) < 1e-7:
            continue
        u = ((x - a[0]) * ez - (z - a[2]) * ex) / determinant
        v = (dx * (z - a[2]) - dz * (x - a[0])) / determinant
        if u >= -1e-6 and v >= -1e-6 and u + v <= 1 + 1e-6:
            hits.append(a[1] + u * (b[1] - a[1]) + v * (c[1] - a[1]))
    if not hits:
        raise ValueError(f'No original triangle at {(x, z)}')
    return max(hits)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--export', type=Path, required=True)
    args = parser.parse_args()
    project = Path(__file__).resolve().parents[2]
    source = project.parent / 'ArtSource/RouteNature'
    source.mkdir(parents=True, exist_ok=True)
    ring_file, patch_file = args.export / 'geo_000.glb', args.export / 'geo_005.glb'
    ring, patch = triangles(ring_file, 'g4'), triangles(patch_file, 'g663')
    strips = []
    for x0, x1 in [(-96, -24), (24, 90)]:
        strip = []
        for x in range(x0, x1 + 1, 2):
            toe = 98.045 + .14 * (.5 + .5 * math.sin(x * .34 + math.sin(x * .13)))
            low, high = height(ring, x - 24, toe), height(patch, x, -199.52)
            assert .15 < high - low < .95, (x, low, high)
            strip.append([x, toe, low, high])
        strips.append(strip)
    report = {
        'kind': 'Original sampled decorative geometry; gameplay heights unchanged',
        'coordinate_system': 'Three metres; X is road-local, Z is SARO site-local in sample rows',
        'columns': ['road_x', 'site_toe_z', 'ring_toe_y', 'corridor_y_at_site100.48'],
        'input_meshes': {'g4': {'file': str(ring_file), 'sha256': hashlib.sha256(ring_file.read_bytes()).hexdigest()},
                        'g663': {'file': str(patch_file), 'sha256': hashlib.sha256(patch_file.read_bytes()).hexdigest()}},
        'protection': 'All vertices inside site z98..100.5, outside |road x|24; original World::MakeLands excludes this front band. No collision, floor, raycast or shadow replacement.',
        'strips': strips,
        'runtime_shape': 'Five profile rows: buried toe, two irregular talus rows, lip at99.98, buried back at100.48',
        'triangles': sum((len(strip) - 1) * 8 for strip in strips),
    }
    text = '// Generated by Tools/routenature/sample_seam.py; source hashes and units: ArtSource/RouteNature/saro-seam-samples.json\n'
    text += 'struct FSeamSample { double X,Toe,Low,High; };\n'
    for i, strip in enumerate(strips):
        text += f'static constexpr FSeamSample Seam{i}[]={{\n'
        text += ''.join(' {' + ','.join(f'{value:.9f}' for value in row) + '},\n' for row in strip)
        text += '};\n'
    output = project / 'Source/Signal47/Private/S47RouteNatureSeam.inl'
    output.write_text(text)
    (source / 'saro-seam-samples.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({'header': str(output), 'triangles': report['triangles'], 'source_rows': sum(map(len, strips))}))


if __name__ == '__main__':
    main()
