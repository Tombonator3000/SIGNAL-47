"""Generate disjoint SARO paving from the original road footprint (no engine/import).
The input GLB is immutable. Convex subtraction removes every shared interior face,
including concrete/asphalt intersections; a pairwise area check guards coplanar overlap.
"""
import argparse, hashlib, json, struct
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
p=argparse.ArgumentParser();p.add_argument('--source',type=Path,default=None);a=p.parse_args()
footprint=json.loads(Path(__file__).with_name('road_footprint.json').read_text())
road=[[tuple(v) for v in t] for t in footprint['triangles_xz_m']]
if a.source:
 source_bytes=a.source.read_bytes();n=struct.unpack_from('<I',source_bytes,12)[0];g=json.loads(source_bytes[20:20+n]);blob=source_bytes[28+n:]
 def read(i):
  q=g['accessors'][i];v=g['bufferViews'][q['bufferView']];count={'SCALAR':1,'VEC2':2,'VEC3':3,'VEC4':4}[q['type']];fmt='<'+{5126:'f',5125:'I',5123:'H'}[q['componentType']]*count
  return [struct.unpack_from(fmt,blob,v.get('byteOffset',0)+q.get('byteOffset',0)+k*v.get('byteStride',struct.calcsize(fmt))) for k in range(q['count'])]
 def triangles(name):
  q=next(m for m in g['meshes'] if m['name']==name)['primitives'][0];v=read(q['attributes']['POSITION']);ids=[i[0] for i in read(q['indices'])] if 'indices' in q else list(range(len(v)))
  return [[(v[i][0],v[i][2]) for i in ids[k:k+3]] for k in range(0,len(ids),3)]
 assert hashlib.sha256(source_bytes).hexdigest()==footprint['source_sha256'], 'Unexpected immutable GLB'
 assert triangles('g432')==[[tuple(v) for v in t] for t in road], 'Footprint differs from source'
def area(p):return sum(p[i][0]*p[(i+1)%len(p)][1]-p[(i+1)%len(p)][0]*p[i][1] for i in range(len(p)))/2 if len(p)>2 else 0

def canonical(p):return p if area(p)>0 else list(reversed(p))
def rect(x0,x1,z0,z1):return [(x0,z0),(x1,z0),(x1,z1),(x0,z1)]
def clip(poly,a,b,inside):
 out=[]
 def side(v):return ((b[0]-a[0])*(v[1]-a[1])-(b[1]-a[1])*(v[0]-a[0]))*(1 if inside else -1)
 for s,e in zip(poly,poly[1:]+poly[:1]):
  ds,de=side(s),side(e)
  if (ds>=0)!=(de>=0):
   t=ds/(ds-de);out.append((s[0]+t*(e[0]-s[0]),s[1]+t*(e[1]-s[1])))
  if de>=0:out.append(e)
 return out

def subtract(poly,cutter):
 remaining=poly;out=[]
 for a,b in zip(cutter,cutter[1:]+cutter[:1]):
  piece=clip(remaining,a,b,False)
  if area(piece)>1e-9:out.append(piece)
  remaining=clip(remaining,a,b,True)
  if area(remaining)<1e-9:break
 return out

def union(polys,exclude=()):
 result=[];occupied=list(exclude)
 for p in polys:
  p=canonical(p);pieces=[p]
  for cutter in occupied:pieces=[q for piece in pieces for q in subtract(piece,cutter)]
  result.extend(pieces);occupied.append(p)
 return result

# One concrete route: highway -> fire-exit ramp, visitor bays -> same route,
# and visitor eastern edge -> annex -> truck-ramp foot. No second gravel ribbon.
paths=union([rect(-20,-9.4,5.1,6.3),rect(-12.2,-11,6.3,10.5),
 rect(-8.725,-7.8,10.5,20.5),rect(-8.3,5.95,11.65,12.75),
 rect(4.85,5.95,12.75,17.7),rect(5.95,7.3,16.6,17.7),
 rect(20.1,39.8,5.9,6.5)])
assert len(road)==30
asphalt=union([rect(-18.2,-7.8,10.5,20.5),rect(-16.5,-9.5,20.5,22),
 rect(20.1,39.8,5.9,18),rect(10,39.8,18,23)]+road,paths)
# Independent intersection check over the final output (including material boundary).
allpolys=paths+asphalt
for i,p in enumerate(allpolys):
 for q in allpolys[:i]:
  overlap=p
  for a,b in zip(q,q[1:]+q[:1]):overlap=clip(overlap,a,b,True)
  assert abs(area(overlap))<1e-7,('overlap',i,area(overlap))
out=['// Generated by Tools/sarosurfaces/build_geometry.py; Three X/Z metres.']
for name,polys in [('Concrete',paths),('Asphalt',asphalt)]:
 tris=[(p[0],p[i],p[i+1]) for p in polys for i in range(1,len(p)-1) if abs(area([p[0],p[i],p[i+1]]))>1e-9]
 out.append(f'static const FVector2D {name}Vertices[]={{')
 for tri in tris:out.append(' '+','.join('{%.9f,%.9f}'%v for v in tri)+',')
 out.append('};');print(name,len(tris),'triangles',sum(area(p) for p in polys),'m2')
(ROOT/'Source/Signal47/Private/S47SaroSurfaceGeometry.inl').write_text('\n'.join(out)+'\n')
print('source SHA256',footprint['source_sha256'],'; disjoint polygons PASS')
