 FVector2D ToRoad(const S47FarmBuildings::FSite& S,double X,double Y)
 {
  const double C=FMath::Cos(S.Yaw),N=FMath::Sin(S.Yaw);
  return FVector2D(S.X+X*C-Y*N,S.Z-X*N-Y*C);
 }
 FVector2D ToLocal(const S47FarmBuildings::FSite& S,double RoadX,double RoadZ)
 {
  const double C=FMath::Cos(S.Yaw),N=FMath::Sin(S.Yaw),Dx=RoadX-S.X,Dz=RoadZ-S.Z;
  return FVector2D(Dx*C-Dz*N,-Dx*N-Dz*C);
 }
