def describe_tree(root):
    files, directories = [], []
    for path in [root, *regular_tree(root)]:
        relative = path.relative_to(root).as_posix()
        mode = format(stat.S_IMODE(path.stat().st_mode), "04o")
        if path.is_dir():
            directories.append({"path": relative, "mode": mode})
        elif relative != PACKAGE_MANIFEST:
            files.append({"path": relative, "bytes": path.stat().st_size, "mode": mode, "sha256": file_hash(path)})
    return files, directories


def make_package_manifest(stage, package_id, build):
    files, directories = describe_tree(stage)
    return {
        "schema": "signal47-chapter09-package-v1",
        "package_id": package_id,
        "base_revision": build["base_revision"],
        "unity_source_sha256": build["unity_source_sha256"],
        "build_payload_sha256": build["build_payload_sha256"],
        "player_sha256": build["player_sha256"],
        "package_payload_sha256": tree_hash((stage / item["path"] for item in files), stage),
        "package_hash_method": "Sorted relative file paths, NUL, file bytes; includes build metadata and package additions; excludes package-manifest.json itself. File modes and directories are recorded separately below.",
        "files": files,
        "directories": directories,
    }


def same_tree(left, right):
    require(describe_tree(left) == describe_tree(right), f"Existing immutable package differs: {right}")
    require((left / PACKAGE_MANIFEST).read_bytes() == (right / PACKAGE_MANIFEST).read_bytes(),
            f"Existing package manifest differs: {right}")
    require(stat.S_IMODE((left / PACKAGE_MANIFEST).stat().st_mode) == stat.S_IMODE((right / PACKAGE_MANIFEST).stat().st_mode),
            f"Existing package manifest permissions differ: {right}")


def write_archive(package, archive):
    # Stable metadata makes reruns byte-identical; stored permission bits are preserved.
    with archive.open("wb") as raw, gzip.GzipFile(filename="", fileobj=raw, mode="wb", mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode="w", format=tarfile.PAX_FORMAT) as tar:
            for path in [package, *regular_tree(package)]:
                name = package.name if path == package else f"{package.name}/{path.relative_to(package).as_posix()}"
                info = tar.gettarinfo(str(path), arcname=name)
                info.uid = info.gid = 0
                info.uname = info.gname = ""
                info.mtime = 0
                info.pax_headers = {}
                if path.is_file():
                    with path.open("rb") as stream:
                        tar.addfile(info, stream)
                else:
                    tar.addfile(info)


def install_exact_file(path, contents, mode=0o644):
    if path.exists():
        require(path.is_file() and not path.is_symlink(), f"Refusing non-regular output: {path}")
        require(path.read_bytes() == contents and stat.S_IMODE(path.stat().st_mode) == mode,
                f"Existing immutable output differs: {path}")
        return
    # Exclusive creation refuses a competing run instead of replacing its result.
    with path.open("xb") as stream:
        stream.write(contents)
    path.chmod(mode)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build-dir", type=Path, default=ROOT / "Artifacts/GauntletLinux")
    parser.add_argument("--expect-source", help="Require this exact tested Unity source SHA-256.")
    parser.add_argument("--label", default="Chapter09", choices=["Chapter09", "Visual10", "NightSky12", "Menu14", "Recovery15", "Archive16", "Workstation18", "Resources19"], help="Identified release family; prior packages are retained.")
    parser.add_argument("--candidate", action="store_true", help="Label the package as awaiting gameplay/performance verification and preserve the default launcher.")
    parser.add_argument("--check-only", action="store_true", help="Read-only build/source verification; create no package or launcher.")
    args = parser.parse_args()
    require(args.label != "Archive16" or args.candidate, "Archive16 is a standalone study; --candidate is required to preserve the default game.")
    build_dir = args.build_dir.resolve()
    build = verify_build(ROOT, build_dir, args.expect_source)
    package_id = args.label + "-" + build["unity_source_sha256"][:12]
    releases = ROOT / "Artifacts/Releases"
    destination = releases / package_id
    archive = releases / f"SIGNAL47-{package_id}-Linux.tar.gz"
    if args.check_only:
        print(json.dumps({"verified": True, "package_id": package_id, "unity_source_sha256": build["unity_source_sha256"],
                          "build_payload_sha256": build["build_payload_sha256"], "planned_directory": str(destination)}, indent=2))
        return
    root_launcher = ROOT / "Spill-SIGNAL47.sh"
    if not args.candidate and (root_launcher.exists() or root_launcher.is_symlink()):
        require(root_launcher.is_file() and not root_launcher.is_symlink(), "Refusing non-regular repository launcher.")
        require(GENERATED_MARKER in root_launcher.read_text(encoding="utf-8"),
                "Spill-SIGNAL47.sh was not generated by this script; preserve and review it before replacing it.")
    releases.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".chapter09-package-", dir=releases) as temporary:
        workspace = Path(temporary)
        stage = workspace / package_id
        shutil.copytree(build_dir, stage, copy_function=shutil.copy2)
        stage.chmod(0o755)
        require(build_payload_hash(stage) == build["build_payload_sha256"], "Build changed during copying; nothing installed.")
        require(json.loads((stage / "build-manifest.json").read_text(encoding="utf-8")) == build,
                "Build manifest changed during copying.")
        state = "working-tree" if build["working_tree_changes"] else "clean"
        require((stage / "build-id.txt").read_text(encoding="utf-8").strip() ==
                f"{build['base_revision']} {state} source-sha256:{build['unity_source_sha256']}",
                "Build identity changed during copying.")
        for name, content, mode in (("START_HER.txt", start_text(package_id, build, args.candidate), 0o644),
                                    ("Start-SIGNAL47.sh", package_launcher(), 0o755)):
            require(not (stage / name).exists(), f"Build already contains reserved package file: {name}")
            (stage / name).write_text(content, encoding="utf-8")
            (stage / name).chmod(mode)
        require(not (stage / PACKAGE_MANIFEST).exists(), "Build already contains a package manifest.")
        package_manifest = make_package_manifest(stage, package_id, build)
        (stage / PACKAGE_MANIFEST).write_text(json.dumps(package_manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        (stage / PACKAGE_MANIFEST).chmod(0o644)
        require(source_hash(ROOT) == build["unity_source_sha256"], "Unity source changed while preparing package; nothing installed.")
        require(build_payload_hash(build_dir) == build["build_payload_sha256"], "Build payload changed while preparing package.")
        staged_archive = workspace / archive.name
        write_archive(stage, staged_archive)
        archive_digest = file_hash(staged_archive)
        if destination.exists() or destination.is_symlink():
            same_tree(stage, destination)
        if archive.exists() or archive.is_symlink():
            require(archive.is_file() and not archive.is_symlink() and file_hash(archive) == archive_digest,
                    f"Existing immutable archive differs: {archive}")
        sidecar = archive.with_name(archive.name + ".sha256")
        checksum = f"{archive_digest}  {archive.name}\n".encode("ascii")
        if sidecar.exists() or sidecar.is_symlink():
            require(sidecar.is_file() and not sidecar.is_symlink() and sidecar.read_bytes() == checksum,
                    f"Existing archive checksum differs: {sidecar}")
        # Only exact, fully checked outputs may be installed. Existing releases stay put.
        if not destination.exists():
            stage.rename(destination)
        if not archive.exists():
            staged_archive.chmod(0o644)
            staged_archive.rename(archive)
        install_exact_file(sidecar, checksum)
        if not args.candidate:
            launcher_temp = workspace / "Spill-SIGNAL47.sh"
            launcher_temp.write_text(repository_launcher(package_id), encoding="utf-8")
            launcher_temp.chmod(0o755)
            os.replace(launcher_temp, root_launcher)
    print(json.dumps({"package_id": package_id, "directory": str(destination), "archive": str(archive),
                      "archive_sha256": archive_digest, "package_payload_sha256": package_manifest["package_payload_sha256"],
                      "launcher": str(destination / "Start-SIGNAL47.sh") if args.candidate else str(root_launcher),
                      "candidate": args.candidate}, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as error:
        print(f"PACKAGING REFUSED: {error}", file=sys.stderr)
        sys.exit(1)
