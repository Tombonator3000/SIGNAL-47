#!/usr/bin/env python3
"""Package the matching Chapter09 Linux build; never build or launch the game."""
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import stat
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
BUILD_METADATA = {"build-manifest.json", "build-id.txt"}
PACKAGE_MANIFEST = "package-manifest.json"
GENERATED_MARKER = "# Generated by Automation/package-chapter09.py."
CHUNK = 1024 * 1024


def require(condition, message):
    if not condition:
        raise ValueError(message)


def file_hash(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(CHUNK), b""):
            digest.update(chunk)
    return digest.hexdigest()


def tree_hash(paths, relative_to):
    """Match stamp-gauntlet-build.py: sorted relative path, NUL, file bytes."""
    digest = hashlib.sha256()
    for path in paths:
        if not path.is_file():
            continue
        digest.update(path.relative_to(relative_to).as_posix().encode("utf-8") + b"\0")
        with path.open("rb") as stream:
            for chunk in iter(lambda: stream.read(CHUNK), b""):
                digest.update(chunk)
    return digest.hexdigest()


def source_hash(root):
    # Preserve the exact base ordering used by the build-stamping script.
    bases = ("Unity/Assets", "Unity/Packages", "Unity/ProjectSettings")
    for base in bases:
        require((root / base).is_dir(), f"Missing source directory: {base}")
    return tree_hash((p for base in bases for p in sorted((root / base).rglob("*"))), root)


def regular_tree(root):
    require(root.is_dir() and not root.is_symlink(), f"Not a regular build/package directory: {root}")
    paths = sorted(root.rglob("*"))
    for path in paths:
        require(not path.is_symlink(), f"Symbolic links are not supported in this release: {path}")
        require(path.is_file() or path.is_dir(), f"Unsupported special file: {path}")
    return paths


def build_payload_hash(build):
    return tree_hash((p for p in regular_tree(build) if p.name not in BUILD_METADATA), build)


def verify_build(root, build, expected_source=None):
    regular_tree(build)
    manifest = json.loads((build / "build-manifest.json").read_text(encoding="utf-8"))
    for name in ("unity_source_sha256", "player_sha256", "build_payload_sha256"):
        require(isinstance(manifest.get(name), str) and re.fullmatch(r"[0-9a-f]{64}", manifest[name]),
                f"Invalid build-manifest field: {name}")
    require(isinstance(manifest.get("base_revision"), str) and re.fullmatch(r"[0-9a-f]{40}", manifest["base_revision"]),
            "Build manifest needs an exact Git revision.")
    require(isinstance(manifest.get("working_tree_changes"), bool), "Build manifest needs its working-tree status.")
    if expected_source:
        require(manifest["unity_source_sha256"] == expected_source, "Build differs from --expect-source; nothing packaged.")
    require(source_hash(root) == manifest["unity_source_sha256"],
            "Current Unity source differs from the tested build-manifest; rebuild and reverify before packaging.")
    for name in ("Signal47.x86_64", "UnityPlayer.so", "Signal47_Data/boot.config", "THIRD_PARTY_NOTICES.md", "VT323-OFL.txt"):
        require((build / name).is_file(), f"Missing runtime or license file: {name}")
    require((build / "Signal47.x86_64").stat().st_mode & 0o111, "The native player is not executable.")
    require(file_hash(build / "Signal47.x86_64") == manifest["player_sha256"], "Native player differs from build-manifest.")
    require(build_payload_hash(build) == manifest["build_payload_sha256"], "Build payload differs from build-manifest.")
    state = "working-tree" if manifest["working_tree_changes"] else "clean"
    expected_id = f"{manifest['base_revision']} {state} source-sha256:{manifest['unity_source_sha256']}"
    require((build / "build-id.txt").read_text(encoding="utf-8").strip() == expected_id,
            "build-id.txt does not match build-manifest.json.")
    return manifest


def package_launcher():
    return """#!/usr/bin/env bash
set -euo pipefail
signal47_release_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
cd -- "$signal47_release_dir"
# Respect an explicitly configured audio server; repair absent desktop socket env only.
if [[ -z "${PULSE_SERVER:-}" ]]; then
  for signal47_runtime_dir in "${XDG_RUNTIME_DIR:-}" "/run/user/$(id -u)"; do
    if [[ -n "$signal47_runtime_dir" && -S "$signal47_runtime_dir/pulse/native" ]]; then
      export XDG_RUNTIME_DIR="$signal47_runtime_dir"
      export PULSE_SERVER="unix:$signal47_runtime_dir/pulse/native"
      break
    fi
  done
fi
exec "./Signal47.x86_64" "$@"
"""


def repository_launcher(package_id):
    return f"""#!/usr/bin/env bash
{GENERATED_MARKER}
set -euo pipefail
signal47_repo_dir="$(cd -- "$(dirname -- "${{BASH_SOURCE[0]}}")" && pwd -P)"
signal47_release="$signal47_repo_dir/Artifacts/Releases/{package_id}/Start-SIGNAL47.sh"
if [[ ! -x "$signal47_release" ]]; then
  printf '%s\\n' 'Den bestemte SIGNAL / 47-pakken mangler eller kan ikke kjøres:' "$signal47_release" >&2
  exit 1
fi
exec "$signal47_release" "$@"
"""


