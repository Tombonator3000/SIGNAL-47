# Focused API scenarios for the Caliche story expansion, followed by real talk/Papers clicks.
# Fixture keys represent observations made elsewhere; they do not prove those event journeys.
# The payphone section separately exercises an actual chapter-five clock of 05:03.
# Run sequentially: python3 tools/storyexpansion.py OUTDIR [1280x800|844x390]
import asyncio, json, os, sys
from playwright.async_api import async_playwright

OUT = sys.argv[1]
W, H = map(int, (sys.argv[2] if len(sys.argv) > 2 else '1280x800').split('x'))
URL = os.environ.get('S47_URL') or 'file://' + os.path.abspath('dist-single/index.html')
checks = []

def check(ok, text):
    checks.append((bool(ok), text))
    print(('PASS ' if ok else 'FAIL ') + text, flush=True)

async def main():
    os.makedirs(OUT, exist_ok=True)
    async with async_playwright() as p:
        browser = await p.chromium.launch(args=['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'])
        pg = await (await browser.new_context(viewport={'width': W, 'height': H})).new_page()
        pg.set_default_timeout(180000)
        errors = []
        pg.on('pageerror', lambda e: errors.append(str(e)))
        # Legacy timing/voice baseline; new defaults are exercised in ensemble.py/serling.py.
        await pg.add_init_script("try{localStorage.setItem('s47.serlingNarrator','false');localStorage.setItem('s47.characterVoices','false');}catch{}")
        await pg.add_init_script('HTMLElement.prototype.requestPointerLock = function() { return Promise.resolve(); };')
        await pg.goto(URL)
        await pg.evaluate('localStorage.clear()')
        await pg.reload()
        await pg.wait_for_selector('button[data-a=start]')
        await pg.click('button[data-a=start]')
        ev = pg.evaluate
        await ev("S47.hold=true; S47.tick(.3); S47.jump('chapter1'); S47.tick(1); S47.setAbductions(false); S47.setPicture('off'); S47.nightEvents.wait=1e9; window.readyTown=S47.world.prepare('diner')")
        await pg.wait_for_function('!!S47.world.town && !!S47.world.diner')
        await ev("S47.world.enter('diner'); S47.player.place(7986.4,2064.6,Math.PI/2); S47.tick(.1)")

        async def tick(seconds): await ev(f'S47.tick({seconds},30)')
        async def hour(seconds):
            # Chapter one deliberately clamps the clock. Talk fixtures update the town clock
            # directly and never claim to be a complete chapter playthrough.
            await ev(f'S47.game.clock={seconds}; S47.world.town.update(S47.runTime(),S47.game.clock)')
        async def use(ident): await ev('(id)=>{S47.game.d.inter.get(id).use();}', ident)
        async def close(): await ev('S47.game.d.ui.close()')
        async def choices(): return await pg.locator('.talk [data-c]').evaluate_all('(bs)=>bs.map(b=>b.dataset.c)')
        async def choose(ident): await pg.locator(f'.talk [data-c="{ident}"]').click(timeout=15000)
        async def lines(): return await pg.locator('.talk-lines').inner_text()
        async def keys(add=(), remove=()):
            await ev('({add,remove})=>{for(const k of remove)S47.townSeen.delete(k);for(const k of add)S47.townSeen.add(k);}', {'add': list(add), 'remove': list(remove)})
        async def reopen(ident): await close(); await use(ident)
        async def no_overflow(name):
            fit = await ev("""(()=>{const e=document.querySelector('.talk'),b=e?.getBoundingClientRect();return !!e&&e.scrollWidth<=e.clientWidth+1&&b.left>=-1&&b.right<=innerWidth+1&&document.documentElement.scrollWidth<=innerWidth+1;})()""")
            check(fit, f'{name}: talk fits the {W}x{H} viewport without horizontal overflow')
        docs = lambda: ev("S47.game.docs.filter(d=>d.id.startsWith('witness-')).sort((a,b)=>a.id.localeCompare(b.id)).map(d=>({...d}))")

        # ---------- four observation-driven follow-ups, using actual P.talk choice buttons ----------
        await hour(2 * 3600 + 35 * 60)
        await keys(remove=['ev:phone1','nickel','ev:boy','ev:cows','ev:car'])
        await use('town:gasWindow')
        check('phone' not in await choices(), 'attendant: an unobserved payphone call supplies no follow-up')
        await keys(add=['ev:phone1','nickel'])
        await reopen('town:gasWindow')
        check('phone' not in await choices(), 'attendant: even with the nickel, his old-road account must be heard first')
        await choose('old')
        check('phone' in await choices(), 'attendant: the old-road account unlocks the observed nickel topic')
        await keys(remove=['nickel'])
        await reopen('town:gasWindow')
        check('phone' not in await choices(), 'attendant: the completed call alone is insufficient without its nickel')
        await keys(add=['nickel'])
        await reopen('town:gasWindow')
        await choose('phone')
        check('That phone takes dimes' in await lines(), 'attendant: showing the nickel receives his specific response')
        check('phone' not in await choices(), 'attendant: the follow-up cannot be filed twice')
        await no_overflow('Attendant')
        await pg.screenshot(path=f'{OUT}/attendant_followup.png', animations='disabled')
        await close()

        await keys(add=['ev:boy'])
        await use('town:amDoor')
        check('boy' not in await choices(), 'Earl: hearing tonight\'s boy does not skip his original conversation')
        await choose('calls')
        check('boy' not in await choices(), 'Earl: his unplayed 1981 reel is required before the new question')
        await keys(remove=['ev:boy'])
        await choose('tape')
        check('boy' not in await choices(), 'Earl: the boy question stays hidden when tonight\'s broadcast was not observed')
        await keys(add=['ev:boy'])
        await reopen('town:amDoor')
        await choose('boy')
        check('BOY / COMET' in await lines() and "haven't played" in await lines(), 'Earl: the programme sheet links the observed call without inventing playback of the 1981 reel')
        check('boy' not in await choices(), 'Earl: the programme sheet is filed once')
        await no_overflow('Earl')
        await close()

        await keys(add=['ev:cows'])
        await use('town:woman')
        check('cattle' not in await choices(), 'woman: an observed herd does not skip her original story')
        await choose('radio')
        check('cattle' not in await choices(), 'woman: her husband\'s missing time must be heard first')
        await keys(remove=['ev:cows'])
        await choose('husband')
        check('cattle' not in await choices(), 'woman: without the observed missing cow there is no new question')
        await keys(add=['ev:cows'])
        await reopen('town:woman')
        await choose('cattle')
        check('Write both numbers' in await lines() and 'He never said' in await lines(), 'woman: both herd counts are recorded while her husband\'s experience remains unknown')
        check('cattle' not in await choices(), 'woman: the account is filed once')
        await no_overflow('Woman')
        await pg.screenshot(path=f'{OUT}/woman_followup.png', animations='disabled')
        await close()

        await keys(add=['ev:car'])
        await use('town:sheriffDoor')
        check('car' not in await choices(), 'deputy: seeing the empty car does not skip his original pin account')
        await choose('map')
        check('car' not in await choices(), 'deputy: the green-pin account is also required')
        await choose('green')
        check('car' not in await choices(), 'deputy: the car follow-up is unavailable before his 04:30 return')
        await close()
        await hour(4 * 3600 + 29 * 60)
        check(await ev("S47.game.d.inter.get('town:sheriffDoor').label()==='Door'"), '04:29: the deputy is still absent')
        await hour(4 * 3600 + 30 * 60)
        await keys(remove=['ev:car'])
        await use('town:sheriffDoor')
        check('car' not in await choices(), '04:30: returning does not create an unobserved patrol-car topic')
        await keys(add=['ev:car'])
        await reopen('town:sheriffDoor')
        await choose('car')
        check('I drove the loop' in await lines() and 'loose sheet' in await lines(), '04:30: the observed car now produces the deputy\'s separate statement')
        check('car' not in await choices(), 'deputy: the statement is filed once')
        await no_overflow('Deputy')
        await close()

        expected = await docs()
        check([d['id'] for d in expected] == ['witness-boy','witness-car','witness-cows','witness-phone'], 'exactly four distinct witness documents exist')
        check(all(d['kind'] == 'hand' and d['stamp'] == 'REYES' for d in expected), 'each witness account is a readable notebook copy')
        await ev('S47.game.openNotebook()')
        await pg.locator('.notebook [data-t="papers"]').click()
        for doc in expected:
            check(await pg.locator(f'.notebook [data-p="papers"] [data-d="{doc["id"]}"]').count() == 1, f'Papers offers {doc["id"]} exactly once')
        await pg.screenshot(path=f'{OUT}/witness_papers.png', animations='disabled')
        await pg.locator('.notebook [data-d="witness-car"]').click()
        check('I drove the loop' in await pg.locator('.docview .text').inner_text(), 'a real Papers click opens the full deputy transcription')
        await pg.screenshot(path=f'{OUT}/witness_document.png', animations='disabled')
        await pg.locator('.docview [data-a="back"]').click()
        await close()

        # Save/Continue reconstructs these static copies from the four actual chosen-topic keys.
        await ev("S47.saveNow('manual',0)")
        await pg.reload()
        await pg.wait_for_selector('button[data-a=cont]:not([disabled])')
        await pg.click('button[data-a=cont]')
        await pg.wait_for_function('S47.started()',polling=200)
        await ev('S47.hold=true; S47.tick(.1); S47.setAbductions(false); S47.nightEvents.wait=1e9')
        check(await docs() == expected, 'Continue restores all four witness documents with exactly the same content')
        await hour(4 * 3600 + 35 * 60)
        await ev("S47.world.enter('diner')")
        await use('town:sheriffDoor')
        check('car' not in await choices(), 'Continue keeps an already asked follow-up unavailable')
        await close()
        check(len(await docs()) == 4, 'revisiting after Continue does not duplicate witness papers')

        # ---------- first call, with explicit event-clock input because chapter one clamps time ----------
        await ev("S47.jump('chapter1'); S47.tick(.2); S47.world.enter('diner'); S47.game.d.ui.close(); S47.nightEvents.wait=1e9")
        await keys(remove=['ev:phone1','ev:phone2','nickel'])
        await ev("for(const k of [...S47.townSeen])if(k.startsWith('mark:'))S47.townSeen.delete(k); S47.townEvents.reset(); S47.player.place(7986.4,2064.6,Math.PI/2); S47.player.update(0,0,0,false)")
        await hour(2 * 3600 + 50 * 60)
        await ev("window.phoneStep=(seconds,extra={})=>{for(let t=0;t<seconds-1e-8;t+=.05)S47.townEvents.update(Math.min(.05,seconds-t),{ok:true,inTown:true,later:false,cam:S47.camera,clock:S47.game.clock,t:S47.runTime()+t,...extra});}; phoneStep(21)")
        check(await ev("S47.townEvents.now==='ringing'"), 'chapter-one call: the first payphone recording is available near the phone')
        await use('town:payphone')
        await ev('phoneStep(46.8)')
        check(await ev("S47.townEvents.now==='line'&&!S47.townSeen.has('ev:phone1')&&!S47.townSeen.has('nickel')"), '46.8 seconds of the first call does not award the complete recording or nickel')
        await ev('phoneStep(.3)')
        check(await ev("S47.townSeen.has('ev:phone1')&&S47.townSeen.has('nickel')&&S47.game.notes.some(n=>n.includes('47 s of the control room printer'))"), 'after 47 seconds the first recording and its 1947 nickel are awarded')

        # ---------- real chapter-five 05:03: the return call, aborted and retried ----------
        await ev("S47.jump('chapter5'); S47.tick(.5); S47.world.enter('diner'); S47.game.d.ui.close(); S47.nightEvents.wait=1e9; S47.townEvents.reset(); S47.game.clock=5*3600+3*60; S47.player.place(7986.4,2064.6,Math.PI/2); S47.tick(.1)")
        check(await ev("S47.game.phase==='ch5'&&S47.game.clock>=5*3600+3*60&&S47.game.clock<5*3600+4*60"), 'the return-call scenario uses the actual chapter-five clock at 05:03')
        await tick(21)
        check(await ev("S47.townEvents.now==='ringing'"), 'at actual 05:03 the second payphone call rings after Room 6')
        await pg.screenshot(path=f'{OUT}/phone_0503_ringing.png', animations='disabled')
        n0 = await ev("S47.game.notes.filter(n=>n.includes('Payphone, Main Street, Caliche, again')).length")
        await ev("""window.phoneAudio=[]; window.phonePlay=S47.audio.play;
          S47.audio.play=function(name,opts){const h=phonePlay.call(this,name,opts);if(h){const stop=h.src.stop.bind(h.src);h.src.stop=(...args)=>{h.stoppedByGame=true;return stop(...args);};phoneAudio.push({name,h});}return h;};0""")
        await use('town:payphone')
        await ev('S47.audio.play=phonePlay;0')
        check(await ev("phoneAudio.filter(x=>x.name==='engineStart'||x.name==='engineOff').length===3 && phoneAudio.filter(x=>x.name==='click').length===11"), 'the return call schedules real engine recordings and all four-plus-seven relay clicks')
        await tick(10)
        check(await ev("S47.townEvents.now==='line'&&!S47.townSeen.has('ev:phone2')"), 'the partial return call has not yet awarded its finding')
        await ev("S47.player.place(7985,2130,0); S47.player.update(0,0,0,false); S47.townEvents.update(.1,{ok:true,inTown:true,later:true,cam:S47.camera,clock:S47.game.clock,t:S47.runTime()})")
        check(await ev("S47.townEvents.now==='none'&&!S47.townSeen.has('ev:phone2')"), 'walking away from the return call aborts it without a completed finding')
        check(await ev('phoneAudio.every(x=>x.h.stoppedByGame)'), 'walking away stops the real scheduled engine and relay sources, including the future clicks')
        check(await ev("S47.game.notes.filter(n=>n.includes('Payphone, Main Street, Caliche, again')).length") == n0, 'the aborted call does not claim that all four and seven relay clicks were heard')
        await ev('window.abortClock=S47.game.clock; S47.game.clock=abortClock+239; S47.player.place(7986.4,2064.6,Math.PI/2); S47.player.update(0,0,0,false); phoneStep(21,{later:true})')
        check(await ev("S47.townEvents.now==='none'"), 'the aborted call cannot retry before four minutes have passed')
        await ev('S47.game.clock=abortClock+241; S47.tick(.1)')
        check(await ev("S47.townEvents.now==='ringing'"), 'after four minutes the unspent return call can ring again')
        await use('town:payphone')
        await tick(46)
        check(await ev("S47.townEvents.now==='line'&&!S47.townSeen.has('ev:phone2')"), '46 seconds into the retry is still an incomplete recording')
        await tick(1.2)
        check(await ev("S47.townEvents.now==='none'&&S47.townSeen.has('ev:phone2')&&S47.townSeen.has('ev:phone1')&&S47.townSeen.has('nickel')"), 'the full 47-second return call completes while preserving the first call and nickel')
        check(await ev("S47.game.notes.filter(n=>n.includes('Payphone, Main Street, Caliche, again')).length") == n0 + 1, 'the completed return call files exactly one observation')
        await tick(25)
        check(await ev("S47.townEvents.now==='none'"), 'the completed return call does not ring a third time')
        # A later natural arrival at the diner is already in the dawn. The generic night
        # cutoff must not close this specific post-Room-6 call before its 05:19 window.
        await ev("S47.townEvents.reset(); S47.townSeen.delete('ev:phone2'); for(const k of [...S47.townSeen]) if(k.startsWith('mark:phone2@')) S47.townSeen.delete(k); S47.game.clock=5*3600+15*60; S47.player.place(7986.4,2064.6,Math.PI/2); S47.tick(.2)")
        await tick(21)
        check(await ev("S47.townEvents.now==='ringing' && S47.sky.uniforms.uDawn.value>=.3"), 'a real 05:15 arrival still hears the return call in the diner dawn')
        await use('town:payphone'); await tick(47.1)
        check(await ev("S47.townSeen.has('ev:phone2') && S47.game.phase==='ch5'"), 'the late return call completes before the chapter-six departure')
        check(not errors, 'no browser runtime errors: ' + '; '.join(errors[:3]))
        with open(f'{OUT}/storyexpansion.json','w') as f:
            json.dump({'scenario':'API setup, real talk/Papers clicks, actual chapter-five phone clock','viewport':[W,H],'checks':checks,'witnesses':expected},f,indent=2)
        await browser.close()
        print(f'{sum(ok for ok,_ in checks)}/{len(checks)} PASS',flush=True)
        sys.exit(0 if all(ok for ok,_ in checks) else 1)

asyncio.run(main())
